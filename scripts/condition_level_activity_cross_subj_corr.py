# -*- coding: utf-8 -*-
"""
===============================================================================
Cross-Subject Similarity Analysis of Task-Level Activation Patterns
Author: Xiaoxuan Lei (McGill University / Mila)
Updated: 2025-01-15

Description
-----------
This script computes how similar task-level activation patterns are
across subjects. For each task and each representation level (“region”
or “network”), it computes:

  1. Within-task correlations:
        corr( subject_i(task), subject_j(task) )
  2. Cross-task correlations:
        corr( subject_i(task), subject_j(other_task) )

Two plots are generated per level:
  (a) <task_level>_<level>_across_subject_similarity.png
        - Per-task grouped boxplots (within vs cross correlations)
  (b) <task_level>_<level>_ALL_TASKS_across_subject_similarity.png
        - Pooled correlations across all tasks

The script supports two task definitions:
  - COARSE: nback, interdms, ctxdm
  - FINE:   nback_loc, nback_ctg, interdms_loc_ABAB, ctxdm_col, etc.
  - BOTH:   run both analyses and save under separate directories

Input Directory Structure
-------------------------
Expected files generated by condition_level_visualization.py:

    results/task_level_avg_activity/<subj>/
        <task>_avg_activation.npy              (region-level vector)
        <task>_network_avg_activation.npy      (network-level vector)

Subjects processed:
    sub-01, sub-02, sub-03, sub-05, sub-06


    

===============================================================================
"""


from pathlib import Path
import itertools
import argparse
import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import ttest_ind


# =========================
# Global Configuration
# =========================
RESULT_ROOT = Path("/project/def-pbellec/xuan/fmri_dataset_project/results/task_level_avg_activity")
OUT_BASE = Path("/project/def-pbellec/xuan/fmri_dataset_project/results/cross_subject_similarity")

SUBJECTS = ["sub-01", "sub-02", "sub-03", "sub-05", "sub-06"]
LEVELS = ["region", "network"]


# =========================
# Helper functions
# =========================

def coarse_task_name(fname: str):
    """From 'nback_loc_avg_activation.npy' → 'nback'."""
    return fname.split("_")[0]


def fine_task_name(fname: str):
    """From 'nback_loc_avg_activation.npy' → 'nback_loc'."""
    parts = fname.split("_")
    if len(parts) < 2:
        return parts[0]
    return "_".join(parts[:2])


def discover_tasks_for_subject(subj_dir: Path, task_level="coarse"):
    """Infer tasks from *_avg_activation.npy files."""

    tasks = set()
    for f in subj_dir.glob("*_avg_activation.npy"):
        name = f.name.replace("_avg_activation.npy", "")
        if "network" in name:
            continue  # skip network here; region defines the task set

        if task_level == "coarse":
            tasks.add(coarse_task_name(name))
        elif task_level == "fine":
            tasks.add(fine_task_name(name))
        else:
            raise ValueError("task_level must be coarse or fine")

    return sorted(tasks)


def safe_corr(a, b):
    """Pearson correlation with robust safety checks."""
    a = np.asarray(a, float)
    b = np.asarray(b, float)
    if a.shape != b.shape:
        return np.nan
    if np.allclose(a, a[0]) or np.allclose(b, b[0]):
        return np.nan
    if np.any(~np.isfinite(a)) or np.any(~np.isfinite(b)):
        return np.nan
    return np.corrcoef(a, b)[0, 1]


def collect_data_for_tasks(result_root, subjects, tasks, task_level):
    """
    For each subject, find the files corresponding to each task (coarse or fine).
    Returns data[level][task][subj] = activation vector
    """

    data = {lvl: {task: {} for task in tasks} for lvl in LEVELS}

    for subj in subjects:
        subj_dir = result_root / subj

        # All region files for this subject
        region_files = list(subj_dir.glob("*_avg_activation.npy"))

        for rf in region_files:
            name = rf.name.replace("_avg_activation.npy", "")
            if "network" in name:
                continue  # skip networks here

            # Determine task name based on task_level
            if task_level == "coarse":
                tname = coarse_task_name(name)
            else:
                tname = fine_task_name(name)

            if tname not in tasks:
                continue

            # Load region vector
            data["region"][tname][subj] = np.load(rf).reshape(-1)

            # Corresponding network-level file
            nf = subj_dir / f"{name}_network_avg_activation.npy"
            if nf.exists():
                data["network"][tname][subj] = np.load(nf).reshape(-1)

    return data


# =========================
# Main Cross-Subject Analysis
# =========================

def analyze_one_task_level(task_level: str):
    """
    Run the entire analysis for either 'coarse' or 'fine'.
    """

    print(f"\n\n====================================")
    print(f" RUNNING TASK LEVEL = {task_level.upper()}")
    print(f"====================================")

    OUT_ROOT = OUT_BASE / task_level
    OUT_ROOT.mkdir(parents=True, exist_ok=True)

    # Discover tasks using the first subject
    example_subj_dir = RESULT_ROOT / SUBJECTS[0]
    tasks = discover_tasks_for_subject(example_subj_dir, task_level=task_level)

    print(f"Detected tasks ({task_level}):", tasks)

    # Load all vectors
    data = collect_data_for_tasks(RESULT_ROOT, SUBJECTS, tasks, task_level)

    # =============================================
    # Loop over LEVELS (region, network)
    # =============================================
    for level in LEVELS:
        print(f"\n--- LEVEL = {level.upper()} ---")

        task_labels = []
        all_within = []
        all_cross = []
        task_pvals = []

        # -----------------------------------------
        # Compute correlation distributions
        # -----------------------------------------
        for task in tasks:

            available = [s for s in SUBJECTS if s in data[level][task]]
            if len(available) < 2:
                print(f"Skipping task {task} (fewer than 2 subjects).")
                continue

            # Within-task correlations
            within = []
            for s1, s2 in itertools.combinations(available, 2):
                r = safe_corr(data[level][task][s1], data[level][task][s2])
                if np.isfinite(r):
                    within.append(r)
            within = np.array(within)

            # Cross-task correlations
            other_tasks = [t for t in tasks if t != task]
            cross = []

            for s1, s2 in itertools.combinations(available, 2):
                v_s1 = data[level][task][s1]
                v_s2 = data[level][task][s2]

                for t2 in other_tasks:
                    if s1 in data[level][t2] and s2 in data[level][t2]:
                        r1 = safe_corr(v_s1, data[level][t2][s2])
                        r2 = safe_corr(data[level][t2][s1], v_s2)
                        if np.isfinite(r1): cross.append(r1)
                        if np.isfinite(r2): cross.append(r2)

            cross = np.array(cross)

            if len(within) == 0 or len(cross) == 0:
                continue

            # Stats
            t_stat, p2 = ttest_ind(within, cross, equal_var=False, nan_policy="omit")
            p_one = p2 / 2 if np.nanmean(within) > np.nanmean(cross) else 1.0

            print(f"{task}: within={np.mean(within):.3f}, cross={np.mean(cross):.3f}, p={p_one:.3g}")

            task_labels.append(task)
            all_within.append(within)
            all_cross.append(cross)
            task_pvals.append(p_one)

        # =====================================================
        # Figure 1: Per-task grouped boxplot
        # =====================================================
        fig, ax = plt.subplots(figsize=(2.0 * len(task_labels), 6))

        plot_data = []
        xticks = []
        xtick_labels = []

        for i, task in enumerate(task_labels):
            plot_data.append(all_within[i])
            plot_data.append(all_cross[i])
            xticks.extend([2*i + 1, 2*i + 2])
            xtick_labels.extend([f"{task}\nwithin", f"{task}\ncross"])

        ax.boxplot(plot_data, positions=xticks, widths=0.6, showfliers=True)
        ax.set_xticks(xticks)
        ax.set_xticklabels(xtick_labels, rotation=45, ha='right')
        ax.set_ylabel("Cross-subject Pearson r")
        ax.set_title(f"{task_level.upper()} | {level.upper()} | Across-Subject Similarity")

        for i, p in enumerate(task_pvals):
            xpos = 2*i + 1.5
            ymax = np.nanmax(plot_data[2*i])
            ax.text(xpos, ymax * 1.05, f"p={p:.2g}", ha='center')

        plt.tight_layout()
        out1 = OUT_ROOT / f"{task_level}_{level}_across_subject_similarity.png"
        plt.savefig(out1, dpi=150)
        plt.close()
        print(f"Saved {out1}")

        # =====================================================
        # Figure 2: pooled all-task boxplot
        # =====================================================
        pooled_within = np.concatenate(all_within)
        pooled_cross = np.concatenate(all_cross)

        t_stat, p2 = ttest_ind(pooled_within, pooled_cross, equal_var=False, nan_policy="omit")
        p_one = p2 / 2 if np.nanmean(pooled_within) > np.nanmean(pooled_cross) else 1.0

        fig2, ax2 = plt.subplots(figsize=(5,6))
        ax2.boxplot([pooled_within, pooled_cross],
                    labels=["within (all tasks)", "cross (all tasks)"],
                    showfliers=True)
        ax2.set_ylabel("Cross-subject Pearson r")
        ax2.set_title(f"{task_level.upper()} | {level.upper()} | ALL TASKS\n"
                      f"within={np.nanmean(pooled_within):.3f}, "
                      f"cross={np.nanmean(pooled_cross):.3f}\n"
                      f"p={p_one:.2g}")

        plt.tight_layout()
        out2 = OUT_ROOT / f"{task_level}_{level}_ALL_TASKS_across_subject_similarity.png"
        plt.savefig(out2, dpi=150)
        plt.close()
        print(f"Saved {out2}")


# =========================
# Entrypoint
# =========================

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--task_level",
                        choices=["coarse", "fine", "both"],
                        default="both",
                        help="Task grouping granularity.")
    args = parser.parse_args()

    if args.task_level == "both":
        analyze_one_task_level("coarse")
        analyze_one_task_level("fine")
    else:
        analyze_one_task_level(args.task_level)


if __name__ == "__main__":
    main()
