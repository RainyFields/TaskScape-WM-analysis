#!/usr/bin/env python3
"""
Generate Valid Vertex Mask

Creates a boolean mask identifying vertices with valid BOLD signal 
(excluding medial wall / zero-variance vertices).

The mask is generated by checking the variance of BOLD signal across
multiple runs/subjects to ensure robustness.

Output:
    - valid_vertex_mask.npy: Boolean array (64984,) where True = valid vertex
    - valid_vertex_mask_info.json: Metadata about the mask

Usage:
    python generate_valid_vertex_mask.py
"""

import numpy as np
import json
from pathlib import Path
import nibabel as nib

# Configuration
DATA_ROOT = Path("/project/def-pbellec/xuan/fmri_dataset_project/data")
FMRI_ROOT = DATA_ROOT / "glasser_resampled"
OUTPUT_DIR = DATA_ROOT
TMASK = 1  # First frame to drop

# Variance threshold for valid vertices
STD_THRESHOLD = 0.1  # Vertices with std < 0.1 are considered invalid


def load_bold_data(ts_path: Path):
    """Load BOLD data from a CIFTI file."""
    Y = nib.load(str(ts_path)).get_fdata(dtype=np.float32)
    Y = Y[TMASK:, :]  # Drop first frame
    return Y


def compute_variance_mask(Y):
    """Compute mask based on signal variance."""
    std_val = np.std(Y, axis=0)
    return std_val > STD_THRESHOLD, std_val


def main():
    print("=" * 70)
    print("GENERATING VALID VERTEX MASK")
    print("=" * 70)
    
    # Find all available subjects
    subjects = sorted([d.name for d in FMRI_ROOT.iterdir() 
                       if d.is_dir() and d.name.startswith("sub-")])
    print(f"Found subjects: {subjects}")
    
    # We'll check multiple runs across subjects to create a robust mask
    all_valid_masks = []
    all_std_values = []
    n_files_checked = 0
    n_vertices = None
    
    for subj in subjects:
        subj_dir = FMRI_ROOT / subj
        sessions = sorted([d.name for d in subj_dir.iterdir() 
                          if d.is_dir() and d.name.startswith("ses-")])
        
        for ses in sessions[:2]:  # Check first 2 sessions per subject
            ses_dir = subj_dir / ses
            ts_files = sorted(ses_dir.glob("*_space-Glasser64k_bold.dtseries.nii"))
            
            for ts_path in ts_files[:2]:  # Check first 2 runs per session
                try:
                    Y = load_bold_data(ts_path)
                    if n_vertices is None:
                        n_vertices = Y.shape[1]
                    
                    valid_mask, std_vals = compute_variance_mask(Y)
                    all_valid_masks.append(valid_mask)
                    all_std_values.append(std_vals)
                    n_files_checked += 1
                    print(f"  Checked: {ts_path.name} - {np.sum(valid_mask):,} valid vertices")
                except Exception as e:
                    print(f"  Error loading {ts_path.name}: {e}")
                    continue
            
            if n_files_checked >= 10:  # Check at least 10 files
                break
        
        if n_files_checked >= 10:
            break
    
    if n_files_checked == 0:
        raise RuntimeError("No BOLD files could be loaded!")
    
    print(f"\nChecked {n_files_checked} files")
    
    # Create consensus mask: vertex is valid if it's valid in ALL checked files
    all_valid_masks = np.array(all_valid_masks)
    consensus_mask = np.all(all_valid_masks, axis=0)
    
    # Also compute mean std across files
    all_std_values = np.array(all_std_values)
    mean_std = np.mean(all_std_values, axis=0)
    
    # Alternative mask based on mean std
    mean_std_mask = mean_std > STD_THRESHOLD
    
    # Use the more conservative mask (intersection)
    final_mask = consensus_mask & mean_std_mask
    
    # Statistics
    n_total = len(final_mask)
    n_valid = np.sum(final_mask)
    n_invalid = n_total - n_valid
    
    print("\n" + "=" * 70)
    print("MASK STATISTICS")
    print("=" * 70)
    print(f"Total vertices:     {n_total:,}")
    print(f"Valid vertices:     {n_valid:,} ({n_valid/n_total*100:.2f}%)")
    print(f"Invalid vertices:   {n_invalid:,} ({n_invalid/n_total*100:.2f}%)")
    print(f"Std threshold:      {STD_THRESHOLD}")
    print("=" * 70)
    
    # Save mask
    mask_path = OUTPUT_DIR / "valid_vertex_mask.npy"
    np.save(mask_path, final_mask)
    print(f"\nSaved mask to: {mask_path}")
    
    # Save metadata
    info = {
        "n_total_vertices": int(n_total),
        "n_valid_vertices": int(n_valid),
        "n_invalid_vertices": int(n_invalid),
        "valid_ratio": float(n_valid / n_total),
        "std_threshold": float(STD_THRESHOLD),
        "n_files_checked": int(n_files_checked),
        "subjects_checked": subjects[:len(subjects)],
        "mask_criterion": "std > 0.1 across all checked files",
        "description": "Boolean mask where True = valid vertex with BOLD signal variance"
    }
    
    info_path = OUTPUT_DIR / "valid_vertex_mask_info.json"
    with open(info_path, "w") as f:
        json.dump(info, f, indent=2)
    print(f"Saved info to: {info_path}")
    
    # Also save the invalid vertex indices for reference
    invalid_indices = np.where(~final_mask)[0]
    invalid_path = OUTPUT_DIR / "invalid_vertex_indices.npy"
    np.save(invalid_path, invalid_indices)
    print(f"Saved invalid indices to: {invalid_path}")
    
    # Save valid vertex indices
    valid_indices = np.where(final_mask)[0]
    valid_path = OUTPUT_DIR / "valid_vertex_indices.npy"
    np.save(valid_path, valid_indices)
    print(f"Saved valid indices to: {valid_path}")
    
    print("\n✅ Done!")
    
    return final_mask, info


if __name__ == "__main__":
    mask, info = main()
